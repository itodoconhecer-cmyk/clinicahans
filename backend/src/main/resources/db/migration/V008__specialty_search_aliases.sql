-- Static patient-language synonyms for the CME specialty catalog.
-- Search terms are accent-free normalized keys and are cached by the application at startup.
CREATE TABLE specialty_search_alias (
  normalized_alias varchar(180) PRIMARY KEY
    CHECK (normalized_alias ~ '^[a-z0-9]+( [a-z0-9]+)*$'),
  specialty_id uuid NOT NULL REFERENCES specialty(id)
);

CREATE INDEX idx_specialty_search_alias_specialty
  ON specialty_search_alias(specialty_id);

COMMENT ON TABLE specialty_search_alias IS
  'Static, accent-normalized search synonyms mapped to CFM/CME specialty records.';

